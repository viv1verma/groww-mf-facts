"""Live NAV from AMFI (Association of Mutual Funds in India).

AMFI publishes every scheme's latest NAV in one public text file, updated
each business evening. It is the official source, free, and needs no API
key. Groww and other platforms show the same NAVs. Groww itself has no public
API, so this is how the app gets "live" data.

File format (semicolon-separated, with section header lines between):
    Scheme Code;ISIN Div Payout/ ISIN Growth;ISIN Div Reinvestment;Scheme Name;Plan;Option;Net Asset Value;Date

NAV values are passed through exactly as published, never generated by the
LLM, because they are structured data with an exact source.
"""
from __future__ import annotations

import threading
import time
import urllib.request
from dataclasses import dataclass

from .net import urlopen
from .schemes import Scheme

AMFI_NAV_URL = "https://portal.amfiindia.com/spages/NAVAll.txt"
AMFI_SOURCE_TITLE = "AMFI — Latest NAV of all mutual fund schemes"
CACHE_SECONDS = 30 * 60


@dataclass
class NavRecord:
    scheme_code: int
    scheme_name: str
    plan: str
    option: str
    nav: str  # kept as published text, e.g. "241.8155"
    date: str  # as published, e.g. "12-Nov-2026"


class NavUnavailable(Exception):
    pass


def parse_nav_file(text: str, codes: set[int] | None = None) -> dict[int, NavRecord]:
    records: dict[int, NavRecord] = {}
    header_cols = None
    for line in text.splitlines():
        parts = [p.strip() for p in line.split(";")]
        if parts and parts[0] == "Scheme Code":
            header_cols = len(parts)
            continue
        if len(parts) < 6 or not parts[0].isdigit():
            continue
        code = int(parts[0])
        if codes is not None and code not in codes:
            continue
        if header_cols == 8 and len(parts) >= 8:
            name, plan, option, nav, date = parts[3], parts[4], parts[5], parts[6], parts[7]
        else:  # Older 6-column layout: plan and option are inside the name.
            name, plan, option, nav, date = parts[3], "", "", parts[4], parts[5]
        try:
            float(nav)
        except ValueError:
            continue  # "N.A." etc.
        records[code] = NavRecord(code, name, plan, option, nav, date)
    return records


class AmfiNavClient:
    def __init__(self, url: str = AMFI_NAV_URL, timeout: float = 10.0, fetch=None):
        self.url = url
        self.timeout = timeout
        self._fetch = fetch or self._download
        self._lock = threading.Lock()
        self._cached: tuple[float, dict[int, NavRecord]] | None = None

    def _download(self) -> str:
        request = urllib.request.Request(self.url, headers={"User-Agent": "mf-facts-prototype/1.0"})
        with urlopen(request, timeout=self.timeout) as response:
            return response.read().decode("utf-8", errors="replace")

    def _all(self) -> dict[int, NavRecord]:
        with self._lock:
            if self._cached and time.time() - self._cached[0] < CACHE_SECONDS:
                return self._cached[1]
            try:
                records = parse_nav_file(self._fetch())
            except Exception as exc:
                if self._cached:  # Serve stale data rather than nothing.
                    return self._cached[1]
                raise NavUnavailable("AMFI NAV file could not be fetched") from exc
            if not records:
                raise NavUnavailable("AMFI NAV file had no records")
            self._cached = (time.time(), records)
            return records

    def for_scheme(self, scheme: Scheme) -> list[tuple[str, NavRecord]]:
        records = self._all()
        out = [(label, records[code]) for label, code in scheme.amfi_codes.items() if code in records]
        if not out:
            raise NavUnavailable(f"No AMFI NAV found for {scheme.name}")
        return out


_client = AmfiNavClient()


def get_nav_client() -> AmfiNavClient:
    return _client
